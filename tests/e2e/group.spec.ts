import path from 'node:path';
import {test,expect} from '../../frontend/node_modules/@playwright/test';
test('group controls, ten graphic renderers, and preview program isolation',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.request.post('/api/pair',{data:{}});
 const previous=await (await page.request.get('/api/group/state')).json();if(previous.group)await page.request.post('/api/group/session/close',{data:{}});
 await page.goto('/');await page.getByRole('button',{name:'Race Control',exact:true}).click();
 await page.getByLabel('League name',{exact:true}).fill('Synthetic UI league');
 await page.getByRole('button',{name:'Create league',exact:true}).click();
 await expect(page.getByLabel('Saved league')).not.toHaveValue('');
 await page.getByRole('button',{name:'Create event',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Race director'})).toBeVisible();
 await page.getByRole('button',{name:'Studio',exact:true}).click();await page.getByRole('button',{name:'Edit',exact:true}).click();
 await page.getByRole('button',{name:'Create workspace',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Draft preview · 1920 × 1080'})).toBeVisible();
 await page.getByText('Add a graphic',{exact:true}).click();
 for(const name of ['Timing tower','Session bar','Flag banner','Race-control message','Driver lower third','Selected-car telemetry','Head-to-head comparison','Track map','Grid/results panel','League/event slate'])await page.getByRole('button',{name:'+ '+name,exact:true}).click();
 await expect(page.locator('.studio-monitors>div').first().locator('.group-graphic')).toHaveCount(8);
 await page.getByRole('button',{name:'Save draft',exact:true}).click();
 await expect(page.getByText('Program revision 0.',{exact:false})).toBeVisible();
 await page.getByRole('button',{name:'Take to program',exact:true}).click();
 await expect(page.getByText('Program revision 1.',{exact:false})).toBeVisible();
 await page.screenshot({path:path.resolve(__dirname,'../../docs/screenshots/group-studio.png'),fullPage:true});
 const current=await (await page.request.get('/api/group/state')).json();
 const workspace=current.workspaces.at(-1);
 const hosting=await page.request.post('/api/group/hosting',{data:{enabled:true,bind:'127.0.0.1',port:18390,origins:['http://127.0.0.1:18390']}});expect(hosting.ok()).toBeTruthy();
 const issued=await (await page.request.post('/api/group/workspaces/'+workspace.id+'/credential',{data:{}})).json();
 await expect.poll(async()=>{try{return (await page.request.get('http://127.0.0.1:18390/group-api/info')).status()}catch{return 0}}).toBe(200);
 const output=await page.context().newPage();await output.goto('http://127.0.0.1:18390/overlay/'+workspace.id+'#access='+issued.credential);
 await expect(output.locator('.group-graphic')).toHaveCount(8);
 await expect(output.locator('body')).toHaveCSS('background-color','rgba(0, 0, 0, 0)');
 await output.reload();await expect(output.locator('.group-graphic')).toHaveCount(8);await output.close();
 await page.request.post('/api/group/hosting',{data:{enabled:false}});
 expect(errors).toEqual([]);
});
