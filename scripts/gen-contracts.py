#!/usr/bin/env python3
"""Generate contract docs and frontend TypeScript from the Python registries.

    python scripts/gen-contracts.py            # write outputs
    python scripts/gen-contracts.py --check    # exit 1 if any output is stale (used by tests/test_contracts_fresh.py)

Outputs (deterministic; never edit by hand):
  docs/architecture/CONTRACTS.md
  frontend/src/domain/channels.generated.ts     telemetry channels (reported/calculated/experimental/unavailable)
  frontend/src/domain/commands.generated.ts     command ids, capability, audit/rate flags
  frontend/src/domain/capabilities.generated.ts capability ids + role matrix
  frontend/src/domain/graphics.generated.ts     graphics templates
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

HEADER_TS = '// GENERATED by scripts/gen-contracts.py - do not edit.\n'


def ts_literal(value) -> str:
    return json.dumps(value, indent=1, sort_keys=True, ensure_ascii=False)


def md_table(headers, rows) -> str:
    def cell(x):
        text = '' if x is None else str(x)
        return text.replace('|', '\\|').replace('\n', ' ')
    out = ['| ' + ' | '.join(headers) + ' |', '|' + '|'.join('---' for _ in headers) + '|']
    out += ['| ' + ' | '.join(cell(c) for c in row) + ' |' for row in rows]
    return '\n'.join(out)


def collect():
    from backend.app import commands_catalog  # noqa: F401  (registers the command catalogue)
    from backend.app.config import Settings
    from backend.app.core import features, permissions
    from backend.app.core.commands import COMMANDS
    from backend.app.core.errors import HTTP_STATUS
    from backend.app.core.version import versions
    from backend.app.telemetry import PARSER_VERSION
    from backend.app.engineer import RULE_SPECS
    from backend.app.group.graphics import GRAPHIC_TEMPLATES
    from backend.app.group.protocol import MESSAGE_TYPES
    from backend.app.storage.exports import EXPORT_FORMATS
    from backend.app.telemetry.derived import all_public_channels
    channels = sorted(all_public_channels(), key=lambda c: (c['group'], c['id']))
    return {
        'channels': channels, 'commands': sorted(COMMANDS.to_public(), key=lambda c: c['id']),
        'capabilities': sorted(({'id': c.id, 'area': c.area, 'description': c.description} for c in permissions.CAPABILITIES),
                               key=lambda c: c['id']),
        'roles': permissions.matrix(), 'rules': [{'id': r.id, **r.public()} for r in RULE_SPECS],
        'graphics': sorted(GRAPHIC_TEMPLATES.to_public(), key=lambda g: g['id']),
        'exports': sorted(EXPORT_FORMATS.to_public(), key=lambda f: f['id']),
        'messages': sorted(MESSAGE_TYPES.to_public(), key=lambda m: m['type']),
        'features': [{'id': f.id, 'stage': f.stage, 'default': f.default, 'description': f.description,
                      'legacy_setting': f.legacy_setting} for f in features.FEATURES],
        'settings': [{'field': name, 'default': (f.default if f.default is not None or f.default_factory is None else f.default_factory()),
                      'annotation': str(f.annotation).replace('typing.', '').replace("<class '", '').replace("'>", ''),
                      'constraints': ', '.join(str(m) for m in f.metadata)}
                     for name, f in Settings.model_fields.items()],
        'result_codes': {str(code): status for code, status in HTTP_STATUS.items()},
        'versions': versions(PARSER_VERSION),
    }


def render_md(d) -> str:
    def dump(v):
        return json.dumps(v, default=str, sort_keys=True) if isinstance(v, (dict, list)) else v
    out = ['# Contracts (generated)', '',
           'Generated by `scripts/gen-contracts.py` from the live registries. **Do not edit**; run the script after changing a',
           'registry (`tests/test_contracts_fresh.py` fails when this file is stale).', '',
           f"Versions: `{json.dumps(d['versions'], sort_keys=True)}`", '']
    out += ['## Telemetry channels', '',
            'Source is `reported` (in the GT7 packet), `calculated` (derived by us), `experimental` (undocumented; gated by',
            '`trust_c_fields`) or `unavailable` (GT7 does not provide it; shown as N/A, never faked). Units are canonical (SI-ish).', '',
            md_table(['id', 'group', 'unit', 'source', 'min variant', 'availability / note'],
                     [(c['id'], c['group'], c['unit'], c['source'], c['min_variant'], c.get('availability', '')) for c in d['channels']]), '']
    out += ['## Commands', '',
            md_table(['id', 'capability', 'audited', 'destructive', 'rate (max, per s)', 'description'],
                     [(c['id'], c['capability'], c['audited'], c['destructive'], c['rate'], c['description']) for c in d['commands']]), '',
            'Result codes → HTTP status: ' + ', '.join(f'`{k}`={v}' for k, v in sorted(d['result_codes'].items())), '']
    out += ['## Capabilities × roles', '']
    roles = sorted(d['roles'])
    out += [md_table(['capability', *roles, 'description'],
                     [(c['id'], *('✓' if c['id'] in d['roles'][r] else '' for r in roles), c['description']) for c in d['capabilities']]), '',
            'Conditional grant: drivers get `telemetry.viewAll` only when the host enabled traffic sharing. Workspace-scoped graphics and',
            'overlay capabilities additionally require ownership/sharing (see `core/permissions.py` scope rules).', '']
    out += ['## Engineer alert rules', '',
            md_table(['id', 'priority', 'persist (s)', 'prerequisite', 'entry', 'exit'],
                     [(r['id'], r['priority'], r['persist'], r['prerequisite'], r['entry'], r['exit']) for r in d['rules']]), '',
            'Priority 0 = critical … 3 = coaching. Cooldown is `Settings.alert_cooldown` (tyre heat has its own per-tyre/global cooldowns).', '']
    out += ['## Graphics templates', '',
            md_table(['id', 'name', 'category', 'size', 'stage', 'required models', 'required sharing'],
                     [(g['id'], g['name'], g.get('category'), f"{g['default_size']['width']}×{g['default_size']['height']}", g.get('stage'),
                       ', '.join(g.get('required_models', [])), ', '.join(g.get('required_sharing', []))) for g in d['graphics']]), '']
    out += ['## Export formats', '',
            md_table(['id', 'name', 'extension', 'supports', 'media type'],
                     [(f['id'], f['name'], f['extension'], ', '.join(f['supports']), f['media_type']) for f in d['exports']]), '']
    out += ['## Group protocol message types (v2 envelope)', '',
            md_table(['type', 'reliability', 'senders', 'schema', 'description'],
                     [(m['type'], m['reliability'], ', '.join(m['roles']), m['schema'], m['description']) for m in d['messages']]), '']
    out += ['## Feature flags', '',
            md_table(['id', 'stage', 'default', 'stored in', 'description'],
                     [(f['id'], f['stage'], f['default'], f['legacy_setting'] or 'feature_flags', f['description']) for f in d['features']]), '']
    out += ['## Settings fields', '',
            md_table(['field', 'default', 'type', 'constraints'],
                     [(s['field'], dump(s['default']), s['annotation'], s['constraints']) for s in d['settings']]), '']
    return '\n'.join(out)


def render_channels_ts(d) -> str:
    rows = [{'id': c['id'], 'label': c['name'], 'unit': c['unit'], 'group': c['group'], 'source': c['source'],
             'minVariant': c['min_variant'], 'description': c.get('availability') or '', 'formatter': c.get('formatter', ''),
             'colorRole': c.get('color_role'), 'sampling': c.get('sampling', 'full')} for c in d['channels']]
    return (HEADER_TS + "import type {ChannelDef} from './channels'\n\n"
            'export const CHANNELS:ChannelDef[]=' + ts_literal(rows) + '\n')


def render_commands_ts(d) -> str:
    ids = [c['id'] for c in d['commands']]
    meta = {c['id']: {'capability': c['capability'], 'audited': c['audited'], 'destructive': c['destructive'],
                      'rate': c['rate']} for c in d['commands']}
    return (HEADER_TS + 'export const GENERATED_COMMAND_IDS=' + ts_literal(ids) + ' as const\n'
            'export type GeneratedCommandId=typeof GENERATED_COMMAND_IDS[number]\n'
            'export const COMMAND_META:Record<string,{capability:string;audited:boolean;destructive:boolean;rate:[number,number]|null}>=' + ts_literal(meta) + '\n')


def render_capabilities_ts(d) -> str:
    ids = [c['id'] for c in d['capabilities']]
    return (HEADER_TS + 'export const CAPABILITY_IDS=' + ts_literal(ids) + ' as const\n'
            'export type CapabilityId=typeof CAPABILITY_IDS[number]\n'
            'export const ROLE_CAPABILITIES:Record<string,readonly CapabilityId[]>=' + ts_literal(d['roles']) + '\n')


def render_graphics_ts(d) -> str:
    rows = [{'id': g['id'], 'name': g['name'], 'category': g.get('category'), 'width': g['default_size']['width'], 'height': g['default_size']['height'],
             'renderer': g.get('renderer'), 'stage': g.get('stage'), 'requiredModels': g.get('required_models', []), 'requiredSharing': g.get('required_sharing', []),
             'lifecycle': g.get('lifecycle', {})} for g in d['graphics']]
    return (HEADER_TS + 'export type GraphicTemplateDef={id:string;name:string;category:string|null;width:number;height:number;stage:string;'
            'renderer:string;requiredModels:string[];requiredSharing:string[];lifecycle:Record<string,unknown>}\n'
            'export const GRAPHIC_TEMPLATES:GraphicTemplateDef[]=' + ts_literal(rows) + '\n')


def outputs() -> dict[Path, str]:
    d = collect()
    src = ROOT / 'frontend' / 'src' / 'domain'
    return {
        ROOT / 'docs' / 'architecture' / 'CONTRACTS.md': render_md(d) + '\n',
        src / 'channels.generated.ts': render_channels_ts(d),
        src / 'commands.generated.ts': render_commands_ts(d),
        src / 'capabilities.generated.ts': render_capabilities_ts(d),
        src / 'graphics.generated.ts': render_graphics_ts(d),
    }


def main(argv) -> int:
    check = '--check' in argv
    stale = []
    for path, text in outputs().items():
        current = path.read_text(encoding='utf-8') if path.exists() else None
        if current != text:
            stale.append(path.relative_to(ROOT).as_posix())
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding='utf-8', newline='\n')
    if check:
        if stale:
            print('Stale generated contracts (run: python scripts/gen-contracts.py):\n  ' + '\n  '.join(stale))
            return 1
        print('Contracts are up to date.')
        return 0
    print('Updated:' if stale else 'Nothing to update.', *stale)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
